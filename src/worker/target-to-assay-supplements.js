import { fetchChemblIndications } from "../lib/target-to-assay/chembl.js";
import { fetchFdaDocuments } from "../lib/target-to-assay/evidence.js";
import { fetchLiteratureSource } from "../lib/target-to-assay/literature.js";
import { providerIssue } from "../lib/target-to-assay/provider-status.js";
import { fetchDevelopmentProfile } from "../lib/target-to-assay/trials.js";

const name = (value) => typeof value === "string" && /^[\p{L}\p{N}][\p{L}\p{N} .()/'’+,-]{0,139}$/u.test(value);
const trialName = (value) => name(value) && !/["\\]/.test(value);
const sources = {
  "fda-documents": { source: "Drugs@FDA", run: fetchFdaDocuments },
  "drug-development": { source: "ClinicalTrials.gov", run: fetchDevelopmentProfile },
  "chembl-indications": { source: "ChEMBL", run: fetchChemblIndications },
  "pubmed-literature": { source: "PubMed", run: fetchLiteratureSource },
};
export const supplementActions = Object.keys(sources);
const cache = new Map();
let active = 0;

function inputFor(action, body) {
  if (action === "chembl-indications") {
    const ids = body?.ids;
    return Array.isArray(ids) && ids.length > 0 && ids.length <= 12 &&
      ids.every((id) => typeof id === "string" && /^CHEMBL\d{1,12}$/.test(id))
      ? [...new Set(ids)].sort() : null;
  }
  if (action === "pubmed-literature") {
    const term = body?.term;
    // Accept only the Title/Abstract expression generated by the Explorer.
    if (typeof term !== "string" || term.length > 3000) return null;
    const token = /"[^"[\]\\\r\n]{1,140}"\[Title\/Abstract\]/g;
    return /^\(T(?: OR T)*\)(?: AND \(T(?: OR T)*\))*$/.test(term.replace(token, "T"))
      && !/(^|[ (])T(?=[ )]|$)/.test(term.replace(token, "")) ? term : null;
  }
  if (!trialName(body?.name) || (body.brand != null && body.brand !== "" && !trialName(body.brand))) return null;
  const aliases = body.aliases ?? [];
  if (!Array.isArray(aliases) || aliases.length > 6 || !aliases.every(trialName)) return null;
  return { name: body.name, brand: body.brand || "", aliases: [...new Set(aliases)].sort() };
}

export async function handleSupplement(action, body, json, requestSignal, fetcher = fetch) {
  const input = inputFor(action, body);
  if (input === null) return json({ error: { code: "invalid_query" } }, 422);
  const key = JSON.stringify([action, input]);
  const cached = cache.get(key);
  if (cached?.expires > Date.now()) return json(cached.value);
  cache.delete(key);
  const { source, run } = sources[action];
  if (active >= 8)
    return json({ error: { code: "rate_limited", source } }, 429, { "Retry-After": "3" });
  active++;
  try {
    const signal = AbortSignal.any([requestSignal, AbortSignal.timeout(12000)]);
    const result = await run(input, { signal, fetcher, withStatus: true });
    const hasData = (result.rows || result.recordIds || []).length > 0;
    const value = { ...result, source, state: result.validationFailures ? "partial" :
      hasData ? "success_with_data" : "success_empty" };
    if (!result.validationFailures && !signal.aborted && (result.xml?.length || 0) <= 512_000) {
      cache.set(key, { value, expires: Date.now() + 5 * 60_000 });
      if (cache.size > 48) cache.delete(cache.keys().next().value);
    }
    return json(value);
  } catch (error) {
    const issue = providerIssue(error);
    return json({ error: { code: issue.state, source } },
      issue.state === "timeout" ? 504 : issue.state === "rate_limited" ? 429 : 502,
      issue.state === "rate_limited" ? { "Retry-After": "3" } : {});
  } finally {
    active--;
  }
}
